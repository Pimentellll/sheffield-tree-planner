"""Write a small SYNTHETIC test terrain in canopy-terrain-context/1 format for UI checks.

It is generated from a formula, flagged synthetic_test=true, and the UI labels it
"SYNTHETIC TEST TERRAIN · NOT SHEFFIELD". Never use it as a stand-in for real data.

    python frontend/scripts/make_test_terrain.py --out <folder>
"""
import argparse, hashlib, json, math, struct
from pathlib import Path

def main():
    p = argparse.ArgumentParser(); p.add_argument("--out", type=Path, required=True); a = p.parse_args()
    cols, rows, step = 60, 50, 2
    dtm, dsm = [], []
    for r in range(rows):
        for c in range(cols):
            g = 100 + 0.1 * c + 2 * math.sin(r / 8)
            block = 12.0 if 20 <= c < 28 and 15 <= r < 22 else 0.0
            dtm.append(g); dsm.append(g + block)
    dsm[5] = float("nan")
    payload = struct.pack(f"<{cols*rows}f", *dtm) + struct.pack(f"<{cols*rows}f", *dsm)
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / "weston-park.bin").write_bytes(payload)
    meta = dict(kind="canopy-terrain-context/1", name="weston-park", title="Synthetic test terrain", synthetic_test=True,
        crs="synthetic grid", box_bng=[0, 0, cols*step, rows*step], spacing_m=step, cols=cols, rows=rows, bin="weston-park.bin",
        bin_sha256=hashlib.sha256(payload).hexdigest(), reduction="formula", vertical_datum="none (synthetic)",
        survey="Generated by make_test_terrain.py", licence="No licence: synthetic", attribution="Synthetic test data.", sources=[],
        stats=dict(dtm_min_m=min(dtm), dtm_max_m=max(dtm), max_height_above_ground_m=12.0, nodata_cells=1),
        boxes=[dict(label="Test box", bng=[20, 20, 80, 70])], markers=[dict(label="Test marker", bng=[48, 62])],
        limitations=["Synthetic formula surface for interface checks only"])
    (a.out / "weston-park.json").write_text(json.dumps(meta, indent=2))
    print("written", a.out)

if __name__ == "__main__":
    main()
